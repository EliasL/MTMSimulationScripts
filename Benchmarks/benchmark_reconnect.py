def read_csv_rows(output_dir: Path, name: str) -> list[dict[str, str]]:
    csv_path = output_dir / name / "macroData.csv"
    if not csv_path.exists():
        return []

    with csv_path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def as_float(row: dict[str, str], key: str, default: float = 0.0) -> float:
    try:
        return float(row.get(key, default))
    except ValueError:
        return default


def as_int(row: dict[str, str], key: str, default: int = 0) -> int:
    try:
        return int(float(row.get(key, default)))
    except ValueError:
        return default


def sum_int(rows: list[dict[str, str]], key: str) -> int:
    return sum(as_int(row, key) for row in rows)


def sudo_is_primed() -> bool:
    try:
        return (
            subprocess.run(
                ["sudo", "-n", "true"],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            ).returncode
            == 0
        )
    except OSError:
        return False


def require_sudo_for_profile() -> None:
    if sudo_is_primed():
        return
    if sys.stdin.isatty():
        print("Profiling uses sudo dtrace. Refreshing sudo now.", flush=True)
        try:
            subprocess.run(["sudo", "-v"], check=True)
        except (OSError, subprocess.CalledProcessError) as exc:
            raise SystemExit(f"Could not refresh sudo credentials: {exc}") from exc
        if sudo_is_primed():
            return
    raise SystemExit(
        "Profiling uses sudo dtrace. Run this once in the same interactive "
        "terminal/session that will run the benchmark, then rerun the benchmark:"
        "\n\n  sudo -v\n"
    )


def run_dtrace_profile(
    pid: int, run_dir: Path, name: str, args: argparse.Namespace
) -> dict[str, object]:
    flamegraph_dir = args.flamegraph_dir.resolve()
    stackcollapse_script = flamegraph_dir / "stackcollapse.pl"
    flamegraph_script = flamegraph_dir / "flamegraph.pl"
    if not stackcollapse_script.exists() or not flamegraph_script.exists():
        raise FileNotFoundError(f"FlameGraph scripts not found in {flamegraph_dir}")

    text_output = run_dir / f"{name}_profile_dtrace.txt"
    folded_output = run_dir / f"{name}_profile_folded.txt"
    svg_output = run_dir / f"{name}_profile.svg"
    stderr_output = run_dir / f"{name}_profile_stderr.txt"

    d_program = (
        f"profile-{args.profile_interval_ms}ms /pid == {pid}/ "
        f"{{ @[ustack()] = count(); }} "
        f"tick-{args.profile_duration}s {{ exit(0); }}"
    )
    dtrace_cmd = [
        "sudo",
        "-n",
        "dtrace",
        "-x",
        f"ustackframes={args.profile_ustackframes}",
        "-n",
        d_program,
    ]

    print(f"Profiling PID {pid} for {args.profile_duration}s", flush=True)
    profile_start = time.perf_counter()
    with text_output.open("wb") as text_file:
        dtrace = subprocess.run(
            dtrace_cmd, cwd=REPO_ROOT, stdout=text_file, stderr=subprocess.PIPE
        )
    profile_seconds = time.perf_counter() - profile_start
    stderr_output.write_bytes(dtrace.stderr)
    if dtrace.returncode != 0:
        stderr_text = dtrace.stderr.decode(errors="replace")
        result = {
            "pid": pid,
            "error": "dtrace failed",
            "returncode": dtrace.returncode,
            "stderr": str(stderr_output),
            "raw": str(text_output),
            "seconds": profile_seconds,
        }
        if "password is required" in stderr_text:
            result["hint"] = "Run sudo -v before starting the profiled benchmark."
        return result

    collapsed = subprocess.run(
        [str(stackcollapse_script)],
        input=text_output.read_bytes(),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if collapsed.returncode != 0:
        stderr_output.write_bytes(stderr_output.read_bytes() + collapsed.stderr)
        return {
            "pid": pid,
            "error": "stackcollapse.pl failed",
            "returncode": collapsed.returncode,
            "stderr": str(stderr_output),
            "raw": str(text_output),
            "seconds": profile_seconds,
        }
    folded_output.write_bytes(collapsed.stdout)

    with svg_output.open("wb") as svg_file:
        flamegraph = subprocess.run(
            [str(flamegraph_script), "--colors=hot", "--hash"],
            input=collapsed.stdout,
            stdout=svg_file,
            stderr=subprocess.PIPE,
        )
    if flamegraph.returncode != 0:
        stderr_output.write_bytes(stderr_output.read_bytes() + flamegraph.stderr)
        return {
            "pid": pid,
            "error": "flamegraph.pl failed",
            "returncode": flamegraph.returncode,
            "stderr": str(stderr_output),
            "raw": str(text_output),
            "folded": str(folded_output),
            "seconds": profile_seconds,
        }

    return {
        "pid": pid,
        "raw": str(text_output),
        "folded": str(folded_output),
        "svg": str(svg_output),
        "stderr": str(stderr_output),
        "seconds": profile_seconds,
        "raw_bytes": text_output.stat().st_size,
        "folded_bytes": folded_output.stat().st_size,
        "svg_bytes": svg_output.stat().st_size,
    }


def run_benchmark_process(
    command: list[str], run_dir: Path, name: str, args: argparse.Namespace
) -> tuple[int, float, dict[str, object]]:
    stdout_path = run_dir / "benchmark_stdout.txt"
    stderr_path = run_dir / "benchmark_stderr.txt"
    memory_path = run_dir / "memory_samples.csv"
    profile: dict[str, object] = {}
    memory_samples: list[tuple[float, int]] = []

    start = time.perf_counter()
    with stdout_path.open("w", encoding="utf-8") as stdout_file, stderr_path.open(
        "w", encoding="utf-8"
    ) as stderr_file:
        process = subprocess.Popen(
            command,
            cwd=run_dir,
            text=True,
            stdout=stdout_file,
            stderr=stderr_file,
        )
        ps_process = psutil.Process(process.pid) if psutil is not None else None
        last_memory_sample = 0.0

        def sample_memory(force: bool = False) -> None:
            nonlocal last_memory_sample
            if ps_process is None:
                return
            now = time.perf_counter()
            if not force and now - last_memory_sample < 1.0:
                return
            try:
                rss_kib = ps_process.memory_info().rss // 1024
            except psutil.Error:
                return
            memory_samples.append((now - start, rss_kib))
            last_memory_sample = now

        sample_memory(force=True)
        if args.profile:
            profile_start_time = time.perf_counter() + args.profile_delay
            while process.poll() is None and time.perf_counter() < profile_start_time:
                sample_memory()
                time.sleep(0.2)
            if process.poll() is None:
                profile = run_dtrace_profile(process.pid, run_dir, name, args)
                if (
                    process.poll() is not None
                    and time.perf_counter() - start
                    < args.profile_delay + args.profile_duration
                ):
                    profile["warning"] = "benchmark exited before profiling finished"
            else:
                profile = {"error": "benchmark exited before profiling started"}
        while process.poll() is None:
            sample_memory()
            time.sleep(0.2)
        returncode = process.wait()

    elapsed = time.perf_counter() - start
    if memory_samples:
        with memory_path.open("w", encoding="utf-8") as f:
            f.write("seconds,rss_kib\n")
            for seconds, rss_kib in memory_samples:
                f.write(f"{seconds:.6f},{rss_kib}\n")
        rss_values = [rss_kib for _, rss_kib in memory_samples]
        profile["memory_samples"] = str(memory_path)
        profile["max_rss_kib"] = max(rss_values)
        profile["last_rss_kib"] = rss_values[-1]
    profile["benchmark_stdout"] = str(stdout_path)
    profile["benchmark_stderr"] = str(stderr_path)
    return returncode, elapsed, profile


def main() -> None:
    global REPO_ROOT
    parser = argparse.ArgumentParser(
        description="Run a small reconnecting MTS2D performance benchmark."
    )
    parser.add_argument("--mts2d-source", type=Path, default=REPO_ROOT)
    parser.add_argument("--exe", type=Path, default=None, help="MTS2D executable")
    parser.add_argument(
        "--build-release",
        action="store_true",
        help="Configure/build build-release/MTS2D before running.",
    )
    parser.add_argument(
        "--build-dir",
        type=Path,
        default=SCRIPT_ROOT / "build-release",
        help="Release build directory used with --build-release.",
    )
    parser.add_argument("--rows", type=int, default=50)
    parser.add_argument("--cols", type=int, default=50)
    parser.add_argument("--threads", type=int, default=3)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--start-load", type=float, default=0.15)
    parser.add_argument("--total-load", type=float, default=0.005)
    parser.add_argument("--load-increment", type=float, default=1e-5)
    parser.add_argument("--initial-guess-noise", type=float, default=0.05)
    parser.add_argument("--lbfgs-corrections", type=int, default=3)
    parser.add_argument("--vtu-frames", type=int, default=5)
    parser.add_argument(
        "--profile",
        action="store_true",
        help="Attach dtrace to the benchmark child PID and generate a flamegraph.",
    )
    parser.add_argument("--profile-duration", type=int, default=20)
    parser.add_argument("--profile-delay", type=float, default=2.0)
    parser.add_argument("--profile-interval-ms", type=int, default=10)
    parser.add_argument("--profile-ustackframes", type=int, default=100)
    parser.add_argument("--flamegraph-dir", type=Path, default=DEFAULT_FLAMEGRAPH_DIR)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=SCRIPT_ROOT / "output" / "benchmark_reconnect",
        help="Base output directory passed to MTS2D.",
    )
    args = parser.parse_args()
    REPO_ROOT = args.mts2d_source.resolve()
    if not (REPO_ROOT / "src" / "Simulation" / "simulation.h").is_file():
        raise FileNotFoundError(f"Not an MTS2D source directory: {REPO_ROOT}")
    if args.profile:
        require_sudo_for_profile()

    exe = args.exe
    if args.build_release:
        release_exe = build_release(args.build_dir.resolve())
        if exe is None:
            exe = release_exe
    if exe is None:
        exe = default_executable()
    exe = exe.resolve()
    if not exe.exists():
        raise FileNotFoundError(f"MTS2D executable not found: {exe}")

    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    name = (
        f"benchmark_reconnect_s{args.rows}x{args.cols}"
        f"_l{args.start_load}_plus_{args.total_load}_t{args.threads}_{stamp}"
    )
    output_dir = args.output_dir.resolve()
    run_dir = output_dir / "runs" / name
    config_path = run_dir / "config.conf"

    write_config(config_path, name, args)

    command = [
        str(exe),
        "-c",
        str(config_path),
        "-o",
        str(output_dir),
        "-r",
    ]

    print(f"Config: {config_path}", flush=True)
    print(f"Output: {output_dir / name}", flush=True)
    returncode, elapsed, profile = run_benchmark_process(command, run_dir, name, args)

    if returncode != 0:
        if "benchmark_stdout" in profile:
            print(Path(str(profile["benchmark_stdout"])).read_text(encoding="utf-8"))
        if "benchmark_stderr" in profile:
            print(Path(str(profile["benchmark_stderr"])).read_text(encoding="utf-8"))
        raise SystemExit(returncode)

    rows = read_csv_rows(output_dir, name)
    row = rows[-1] if rows else {}
    final_load = as_float(row, "load", (args.start_load + args.total_load))
    steps = as_int(row, "load_step")
    load_advanced = final_load - args.start_load
    vtu_files = sum(1 for _ in (output_dir / name).rglob("*.vtu"))
    summary = {
        "name": name,
        "executable": str(exe),
        "config": str(config_path),
        "output": str(output_dir / name),
        "wall_seconds": elapsed,
        "start_load": args.start_load,
        "final_load": final_load,
        "total_load": args.total_load,
        "load_advanced": load_advanced,
        "load_per_second": load_advanced / elapsed if elapsed > 0 else 0.0,
        "steps": steps,
        "steps_per_second": steps / elapsed if elapsed > 0 else 0.0,
        "nr_iterations": as_int(row, "nr_iterations"),
        "nr_func_evals": as_int(row, "nr_func_evals"),
        "nr_edge_flips": sum_int(rows, "nr_edge_flips"),
        "nr_total_edge_flips": sum_int(rows, "nr_total_edge_flips"),
        "nr_steps_with_edge_flips": sum(
            1 for row in rows if as_int(row, "nr_total_edge_flips") > 0
        ),
        "vtu_files": vtu_files,
        "max_rss_kib": profile.get("max_rss_kib"),
        "last_rss_kib": profile.get("last_rss_kib"),
        "memory_samples": profile.get("memory_samples"),
    }
    if args.profile:
        summary["profile"] = profile

    summary_path = run_dir / "summary.json"
    summary_path.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")

    print(json.dumps(summary, indent=2))
    print(f"Summary: {summary_path}")
    if args.profile and "error" in profile:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
