def default_executable() -> Path:
    release_exe = SCRIPT_ROOT / "build-release" / "MTS2D"
    if release_exe.exists():
        return release_exe
    return REPO_ROOT / "build-release" / "MTS2D"


def run_command(command: list[str], cwd: Path | None = None) -> None:
    print("+ " + " ".join(command), flush=True)
    subprocess.run(command, cwd=REPO_ROOT if cwd is None else cwd, check=True)


def build_release(build_dir: Path) -> Path:
    if not build_dir.exists():
        run_command(
            [
                "cmake",
                "-S",
                str(REPO_ROOT),
                "-B",
                str(build_dir),
                "-DCMAKE_BUILD_TYPE=Release",
            ]
        )
    run_command(["cmake", "--build", str(build_dir), "--target", "MTS2D"])
    return build_dir / "MTS2D"


